    fold_recalls = []
    fold_f1s = []

    # Set up K-Fold cross-validation
    kf = KFold(n_splits=k_folds, shuffle=True, random_state=42)

    # For plotting
    train_losses_all_folds = []
    val_losses_all_folds = []
    val_accuracies_all_folds = []

    # For each fold
    for fold, (train_idx, val_idx) in enumerate(kf.split(data)):
        print(f"\nTraining fold {fold+1}/{k_folds}...")

        # Split data
        train_data = [data[i] for i in train_idx]
        val_data = [data[i] for i in val_idx]

        # Create vocabulary from training data for this fold
        vocab = build_vocabulary(train_data)
        max_length = min(100, get_avg_length(train_data))  # Limit to 100 tokens max

        # Load GloVe embeddings
        glove_file = download_glove(embedding_dim)
        embedding_matrix = load_glove_embeddings(glove_file, vocab, embedding_dim)

        # Create datasets
        train_dataset = SentimentDataset(train_data, vocab, embedding_matrix, max_length, num_classes)
        val_dataset = SentimentDataset(val_data, vocab, embedding_matrix, max_length, num_classes)

        # Create dataloaders
        batch_size = 32
        train_loader = DataLoader(train_dataset, batch_size=batch_size, shuffle=True)
        val_loader = DataLoader(val_dataset, batch_size=batch_size)

        # Initialize model
        if model_class == FeedForwardNN:
            model = model_class(len(vocab), embedding_dim, num_classes=num_classes, embedding_matrix=embedding_matrix, dropout_rate=0.3)
        else:  # LSTM
            model = model_class(len(vocab), embedding_dim, num_classes=num_classes, embedding_matrix=embedding_matrix, dropout_rate=0.3)

        # Set up optimizer and criterion
        criterion = nn.CrossEntropyLoss() if num_classes > 2 else nn.BCELoss()
        optimizer = optim.Adam(model.parameters(), lr=0.001, weight_decay=1e-4)

        # Train model
        model, train_losses, val_losses, val_accuracies = train_model(
            model, train_loader, val_loader, criterion, optimizer,
            num_epochs=10, binary=(num_classes == 2), patience=3
        )

        # Evaluate model
        model.eval()

        # Get predictions
        all_preds = []
        all_labels = []
        device = torch.device('cuda' if torch.cuda.is_available() else 'cpu')

        with torch.no_grad():
            for inputs, labels in val_loader:
                inputs, labels = inputs.to(device), labels.to(device)
                outputs = model(inputs)

                if num_classes == 2:
                    predictions = (outputs.squeeze() > 0.5).float()
                else:
                    predictions = torch.argmax(outputs, dim=1)

                all_preds.extend(predictions.cpu().numpy())
                all_labels.extend(labels.cpu().numpy())

        # Calculate metrics
        accuracy = accuracy_score(all_labels, all_preds)

        if num_classes == 2:
            precision = precision_score(all_labels, all_preds)
            recall = recall_score(all_labels, all_preds)
            f1 = f1_score(all_labels, all_preds)
        else:
            precision = precision_score(all_labels, all_preds, average='macro')
            recall = recall_score(all_labels, all_preds, average='macro')
            f1 = f1_score(all_labels, all_preds, average='macro')

        print(f"\nFold {fold+1} Results:")
        print(f"Accuracy: {accuracy:.4f}")
        print(f"Precision: {precision:.4f}")
        print(f"Recall: {recall:.4f}")
        print(f"F1 Score: {f1:.4f}")

        # Store metrics
        fold_accuracies.append(accuracy)
        fold_precisions.append(precision)
        fold_recalls.append(recall)
        fold_f1s.append(f1)

        # Store training curves
        train_losses_all_folds.append(train_losses)
        val_losses_all_folds.append(val_losses)
        val_accuracies_all_folds.append(val_accuracies)

    # Calculate average metrics
    avg_accuracy = np.mean(fold_accuracies)
    avg_precision = np.mean(fold_precisions)
    avg_recall = np.mean(fold_recalls)
    avg_f1 = np.mean(fold_f1s)

    print("\n==== Cross-Validation Results ====")
    print(f"Average Accuracy: {avg_accuracy:.4f}")
    print(f"Average Precision: {avg_precision:.4f}")
    print(f"Average Recall: {avg_recall:.4f}")
    print(f"Average F1 Score: {avg_f1:.4f}")

    # Return metrics and training curves
    metrics = {
        'accuracy': avg_accuracy,
        'precision': avg_precision,
        'recall': avg_recall,
        'f1': avg_f1,
        'fold_accuracies': fold_accuracies,
        'fold_precisions': fold_precisions,
        'fold_recalls': fold_recalls,
        'fold_f1s': fold_f1s,
        'train_losses': train_losses_all_folds,
        'val_losses': val_losses_all_folds,
        'val_accuracies': val_accuracies_all_folds
    }

    return metrics

