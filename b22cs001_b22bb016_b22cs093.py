class SentimentDataset(Dataset):
    def __init__(self, data, vocab, embedding_matrix, max_length, num_classes):
        self.data = data
        self.vocab = vocab
        self.embedding_matrix = embedding_matrix
        self.max_length = max_length
        self.num_classes = num_classes

        # Create label mapping if needed
        self.label_mapping = None
        if num_classes == 3:
            # Check if we need to convert string labels to integers
            for _, label in data:
                if isinstance(label, str):
                    self.label_mapping = {'Negative': 0, 'Neutral': 1, 'Positive': 2,
                                         'negative': 0, 'neutral': 1, 'positive': 2,
                                         '0': 0, '1': 1, '2': 2}
                    print(f"Created label mapping for string labels: {self.label_mapping}")
                    break

    def __len__(self):
        return len(self.data)

    def __getitem__(self, idx):
        text, label = self.data[idx]
        indices = text_to_indices(text, self.vocab, self.max_length)

        # Convert string labels to integers if mapping exists
        if self.label_mapping is not None and isinstance(label, str):
            if label in self.label_mapping:
                label = self.label_mapping[label]
            else:
                try:
                    label = int(label)
                except (ValueError, TypeError):
                    print(f"Warning: Unknown label '{label}', defaulting to 0")
                    label = 0

        # Handle numeric labels that might be strings
        if isinstance(label, str):
            try:
                label = int(float(label))
            except (ValueError, TypeError):
                print(f"Warning: Could not convert label '{label}' to int, defaulting to 0")
                label = 0

        # Ensure label is the correct numeric type
        if not isinstance(label, (int, float)):
            print(f"Warning: Label '{label}' is not numeric (type: {type(label)}), defaulting to 0")
            label = 0

        # Convert label to tensor
        if self.num_classes == 2:  # Binary
            label_tensor = torch.tensor(float(label), dtype=torch.float32)
        else:  # Multiclass
            label_tensor = torch.tensor(int(label), dtype=torch.long)

        return torch.tensor(indices, dtype=torch.long), label_tensor

# Feed-Forward Neural Network for Sentiment Analysis with Embeddings
class FeedForwardNN(nn.Module):
    def __init__(self, vocab_size, embedding_dim, hidden1_size=256, hidden2_size=128, num_classes=2, embedding_matrix=None, dropout_rate=0.3):
        super(FeedForwardNN, self).__init__()

        self.embedding = nn.Embedding(vocab_size, embedding_dim)

        if embedding_matrix is not None:
            self.embedding.weight = nn.Parameter(torch.FloatTensor(embedding_matrix))
            self.embedding.weight.requires_grad = True

        self.flatten = nn.Flatten()
        self.fc1 = nn.Linear(embedding_dim * 100, hidden1_size)
        self.bn1 = nn.BatchNorm1d(hidden1_size)
        self.relu1 = nn.ReLU()
        self.dropout1 = nn.Dropout(dropout_rate)

        self.fc2 = nn.Linear(hidden1_size, hidden2_size)
        self.bn2 = nn.BatchNorm1d(hidden2_size)
        self.relu2 = nn.ReLU()
        self.dropout2 = nn.Dropout(dropout_rate)

        if num_classes == 2:
            self.output = nn.Linear(hidden2_size, 1)
            self.sigmoid = nn.Sigmoid()
        else:
            self.output = nn.Linear(hidden2_size, num_classes)

    def forward(self, x):
        x = self.embedding(x)
        x = self.flatten(x)

        x = self.fc1(x)
        x = self.bn1(x)
        x = self.relu1(x)
        x = self.dropout1(x)

        x = self.fc2(x)
        x = self.bn2(x)
        x = self.relu2(x)
        x = self.dropout2(x)

        if hasattr(self, 'sigmoid'):
            return self.sigmoid(self.output(x))
        else:
            return self.output(x)

class LSTMNN(nn.Module):
    def __init__(self, vocab_size, embedding_dim, hidden_size=256, num_classes=2, embedding_matrix=None, dropout_rate=0.3):
        super(LSTMNN, self).__init__()

        self.embedding = nn.Embedding(vocab_size, embedding_dim)

        if embedding_matrix is not None:
            self.embedding.weight = nn.Parameter(torch.FloatTensor(embedding_matrix))
            self.embedding.weight.requires_grad = True

        self.lstm = nn.LSTM(embedding_dim, hidden_size, batch_first=True)
        self.dropout = nn.Dropout(dropout_rate)

        # For batch normalization in LSTM, we need to handle the sequence dimension properly
        self.bn = nn.BatchNorm1d(hidden_size)

        if num_classes == 2:
            self.output = nn.Linear(hidden_size, 1)
            self.sigmoid = nn.Sigmoid()
        else:
            self.output = nn.Linear(hidden_size, num_classes)

    def forward(self, x):
        x = self.embedding(x)
        lstm_out, (h_n, _) = self.lstm(x)
        x = h_n.squeeze(0)

        # Apply batch normalization
        x = self.bn(x)

        # Apply dropout before final classification
        x = self.dropout(x)

        if hasattr(self, 'sigmoid'):
            return self.sigmoid(self.output(x))
        else:
            return self.output(x)

def evaluate_model(model, data_loader, criterion, binary=True):
    device = torch.device('cuda' if torch.cuda.is_available() else 'cpu')
    model.eval()

    all_preds = []
    all_labels = []
    total_loss = 0

    with torch.no_grad():
        for inputs, labels in data_loader:
            inputs, labels = inputs.to(device), labels.to(device)

            outputs = model(inputs)

            if binary:
                outputs_squeezed = outputs.squeeze()
                loss = criterion(outputs_squeezed, labels)
                predictions = (outputs_squeezed > 0.5).float()
            else:
                loss = criterion(outputs, labels)
                predictions = torch.argmax(outputs, dim=1)

            total_loss += loss.item()
            all_preds.extend(predictions.cpu().numpy())
            all_labels.extend(labels.cpu().numpy())

    accuracy = accuracy_score(all_labels, all_preds)
    avg_loss = total_loss / len(data_loader)
    return accuracy, avg_loss

def train_model(model, train_loader, dev_loader, criterion, optimizer, num_epochs=10, binary=True, patience=3):
    device = torch.device('cuda' if torch.cuda.is_available() else 'cpu')
    model.to(device)

    train_losses = []
    dev_losses = []
    dev_accuracies = []
    best_accuracy = 0
    best_model_weights = None

    # Early stopping parameters
    patience_counter = 0
    best_epoch = 0

    for epoch in range(num_epochs):
        model.train()
        total_loss = 0

        for inputs, labels in train_loader:
            inputs, labels = inputs.to(device), labels.to(device)

            optimizer.zero_grad()
            outputs = model(inputs)

            if binary:
                outputs = outputs.squeeze()

            loss = criterion(outputs, labels)
            loss.backward()
            optimizer.step()

            total_loss += loss.item()

        avg_loss = total_loss / len(train_loader)
        train_losses.append(avg_loss)

        # Evaluate on dev set
        model.eval()
        dev_accuracy, dev_loss = evaluate_model(model, dev_loader, criterion, binary=binary)
        dev_accuracies.append(dev_accuracy)
        dev_losses.append(dev_loss)

        print(f'Epoch {epoch+1}/{num_epochs}, Train Loss: {avg_loss:.4f}, Dev Loss: {dev_loss:.4f}, Dev Accuracy: {dev_accuracy:.4f}')

        # Save best model and check for early stopping
        if dev_accuracy > best_accuracy:
            best_accuracy = dev_accuracy
            best_model_weights = model.state_dict().copy()
            best_epoch = epoch
            patience_counter = 0  # Reset counter
        else:
            patience_counter += 1
            if patience_counter >= patience:
                print(f'Early stopping triggered after epoch {epoch+1}. Best accuracy was at epoch {best_epoch+1}.')
                break

    # Load the best model weights
    model.load_state_dict(best_model_weights)
    print(f"Using best model from epoch {best_epoch+1} with accuracy: {best_accuracy:.4f}")

    return model, train_losses, dev_losses, dev_accuracies

