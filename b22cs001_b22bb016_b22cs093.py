# Load GloVe embeddings
def load_glove_embeddings(embedding_file, vocab, embedding_dim=100):
    print(f"Loading GloVe embeddings from {embedding_file}...")

    # Initialize embedding matrix with random values
    embedding_matrix = np.random.uniform(-0.25, 0.25, (len(vocab), embedding_dim))

    # Special tokens get zeros
    embedding_matrix[0] = np.zeros(embedding_dim)  # PAD token

    # Load pre-trained GloVe embeddings for words in our vocabulary
    with open(embedding_file, 'r', encoding='utf-8') as f:
        for line in f:
            values = line.split()
            word = values[0]
            if word in vocab:
                embedding_matrix[vocab[word]] = np.array(values[1:], dtype=np.float32)

    print(f"Loaded {embedding_dim}-dimensional GloVe embeddings")
    return embedding_matrix

