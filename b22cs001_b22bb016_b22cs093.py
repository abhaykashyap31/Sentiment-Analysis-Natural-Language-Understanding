# Tokenize text using spaCy
def tokenize(text):

    # Ensure text is a string
    if not isinstance(text, str):
        text = str(text)


    # Convert to lowercase
    text = text.lower()

    # Replace URLs with a special token
    text = re.sub(r'https?://\S+|www\.\S+', ' URL ', text)

    # Replace mentions with a special token (for Twitter data)
    text = re.sub(r'@\w+', ' MENTION ', text)

    # Replace hashtags with the word
    text = re.sub(r'#(\w+)', r'\1', text)

    # Replace emojis with words
    text = re.sub(r'[^\w\s,.]', ' ', text)

    # Normalize whitespace
    text = re.sub(r'\s+', ' ', text).strip()

    # Tokenize with spaCy
    doc = nlp(text)

    # Filter out stopwords and punctuation
    tokens = []
    for token in doc:
        if not token.is_stop and not token.is_punct and len(token.text) > 1:
            tokens.append(token.text)

    return tokens

# Build vocabulary from training data
def build_vocabulary(data, min_freq=5):
    word_counts = Counter()

    # Count word frequencies
    for text, _ in data:
        tokens = tokenize(text)
        word_counts.update(tokens)

    # Create vocabulary with words that appear at least min_freq times
    vocab = {'PAD': 0, 'UNK': 1}
    idx = 2

    for word, count in word_counts.items():
        if count >= min_freq:
            vocab[word] = idx
            idx += 1

    return vocab

# Calculate average sentence length
def get_avg_length(data):
    total_tokens = 0
    total_sentences = len(data)

    for text, _ in data:
        tokens = tokenize(text)
        total_tokens += len(tokens)

    return int(total_tokens / total_sentences)

# Convert text to indices
def text_to_indices(text, vocab, max_length):
    tokens = tokenize(text)
    indices = []

    for token in tokens[:max_length]:
        if token in vocab:
            indices.append(vocab[token])
        else:
            indices.append(vocab['UNK'])

    # Pad to max_length
    indices = indices + [vocab['PAD']] * (max_length - len(indices))

    return indices

